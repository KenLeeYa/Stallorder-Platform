export function getAdminApiError(
  locale: AppLocale,
  payload: unknown,
  fallback: AdminMessageKey = "Operation failed. Try again later.",
) {
  const record = payload && typeof payload === "object" && !Array.isArray(payload)
    ? payload as Record<string, unknown>
    : {};
  const code = typeof record.code === "string"
    ? record.code
    : typeof record.errorCode === "string"
      ? record.errorCode
      : null;
  const key = code ? errorCodeMessageKeys[code] : null;
  if (key) return getAdminMessage(locale, key);
  if (locale === "zh-TW" && typeof record.error === "string" && record.error.trim()) {
    return record.error;
  }
  return getAdminMessage(locale, fallback);
}
