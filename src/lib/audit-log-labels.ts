export function auditActionLabel(action: string) {
  const exactLabel = actionLabels[action];
  if (exactLabel) return exactLabel;

  const labels = action.split("_").map((token) => actionTokenLabels[token]);
  return labels.length > 0 && labels.every(Boolean)
    ? labels.join(" · ")
    : "其他系統操作";
}

export function auditEntityTypeLabel(entityType: string) {
  return entityTypeLabels[entityType] ?? "其他系統資料";
}
