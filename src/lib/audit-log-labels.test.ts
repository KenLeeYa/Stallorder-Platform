describe("audit log labels", () => {
  it("translates login and authorization events into merchant-friendly Traditional Chinese", () => {
    expect(auditActionLabel("OAUTH_LOGIN_SUCCEEDED")).toBe("第三方登入成功");
    expect(auditActionLabel("LOGIN_REJECTED_ORIGIN")).toBe("登入來源未通過驗證");
    expect(auditActionLabel("AUTHORIZATION_DENIED")).toBe("權限驗證遭拒");
  });

  it("translates common opening and order events", () => {
    expect(auditActionLabel("MERCHANT_GO_LIVE")).toBe("商家正式啟用");
    expect(auditActionLabel("MERCHANT_SETUP_STEP_COMPLETED")).toBe("開店設定步驟已完成");
    expect(auditActionLabel("MERCHANT_APPLICATION_SUBMITTED")).toBe("商家申請已送出");
    expect(auditActionLabel("ORDER_PACKAGE_ASSIGNED")).toBe("訂單方案已指派");
  });

  it("translates known targets and safely groups unknown engineering codes", () => {
    expect(auditEntityTypeLabel("AUTH_SESSION")).toBe("登入工作階段");
    expect(auditEntityTypeLabel("PRODUCT_BUNDLE_CHOICE")).toBe("套餐選項");
    expect(auditEntityTypeLabel("UNRECOGNIZED_TARGET")).toBe("其他系統資料");
  });

  it("builds a readable label for supported dynamic action combinations", () => {
    expect(auditActionLabel("MARKET_EVENT_CREATE")).toBe("市集 · 活動 · 建立");
    expect(auditActionLabel("UNKNOWN_ENGINEERING_EVENT")).toBe("其他系統操作");
  });

  it("keeps the actual AuditLog writer inventory complete and unique", () => {
    expect(actualAuditActions).toHaveLength(260);
    expect(new Set(actualAuditActions)).toHaveProperty("size", 260);
    expect(actualAuditEntityTypes).toHaveLength(77);
    expect(new Set(actualAuditEntityTypes)).toHaveProperty("size", 77);
  });

  it.each(actualAuditActions)("localizes actual audit action %s", (action) => {
    const label = auditActionLabel(action);
    expect(label).not.toBe("其他系統操作");
    expect(label).not.toContain(action);
    expect(label).not.toMatch(/[A-Z0-9]+(?:_[A-Z0-9]+)+/);
  });

  it.each(actualAuditEntityTypes)("localizes actual audit entity type %s", (entityType) => {
    const label = auditEntityTypeLabel(entityType);
    expect(label).not.toBe("其他系統資料");
    expect(label).not.toContain(entityType);
    expect(label).not.toMatch(/[A-Z0-9]+(?:_[A-Z0-9]+)+/);
  });
});
